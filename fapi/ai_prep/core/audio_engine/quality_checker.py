"""
Audio & Transcript Quality Checker for AI Prep.

Detects Whisper hallucinations, repetitive phrases/loops, abnormal speaking rates,
and silent gaps to ensure transcript integrity before dispatching to LLM evaluation.
"""

import re
import logging
from typing import Dict, Any, List, Optional

logger = logging.getLogger("wbl.ai_prep.audio_engine.quality_checker")


def detect_repetition_loops(text: str, min_repeat_count: int = 3, min_phrase_len: int = 4) -> bool:
    """
    Detects hallucinated repetition loops characteristic of Whisper on silent/low-SNR audio.
    e.g., "Thank you. Thank you. Thank you." or repeated identical 4+ word sentences.
    """
    if not text or len(text.strip()) == 0:
        return False

    cleaned = " ".join(text.split()).strip()
    words = cleaned.split()
    if len(words) < min_phrase_len * min_repeat_count:
        return False

    # Check for repeated n-grams
    for n in range(min_phrase_len, 12):
        if len(words) < n * min_repeat_count:
            break
        for i in range(len(words) - n * min_repeat_count + 1):
            phrase = " ".join(words[i:i + n]).lower()
            # Count consecutive occurrences of phrase
            occurrences = 1
            idx = i + n
            while idx + n <= len(words):
                next_phrase = " ".join(words[idx:idx + n]).lower()
                if next_phrase == phrase:
                    occurrences += 1
                    idx += n
                    if occurrences >= min_repeat_count:
                        logger.warning("Repetition loop detected (%d occurrences): '%s'", occurrences, phrase)
                        return True
                else:
                    break
    return False


def deduplicate_repetitive_loops(text: str) -> str:
    """Removes repetitive trailing hallucination loops from text if detected."""
    if not text:
        return ""
    words = text.split()
    if len(words) < 12:
        return text

    # Remove repeated 3+ word trailing loops
    for n in range(3, 8):
        if len(words) < n * 3:
            continue
        trailing = " ".join(words[-n:]).lower()
        prev = " ".join(words[-2 * n:-n]).lower()
        prev2 = " ".join(words[-3 * n:-2 * n]).lower()
        if trailing == prev == prev2:
            # Cut off the repeating tail
            words_cut = words[:-2 * n]
            return " ".join(words_cut)
    return text


def validate_transcript_quality(
    transcript_text: str,
    duration_seconds: float,
    word_timestamps: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Runs quality audits on transcript generated by Whisper.
    Returns audit findings and cleaned text.
    """
    warnings: List[str] = []
    text = (transcript_text or "").strip()
    words = text.split()
    word_count = len(words)

    # 1. Speaking rate (WPM) check
    duration_min = max(0.01, duration_seconds / 60.0)
    wpm = word_count / duration_min

    if duration_seconds > 30 and word_count < 5:
        warnings.append(f"Insufficient speech content: only {word_count} words in {round(duration_seconds, 1)}s")
    elif wpm > 320:
        warnings.append(f"Abnormally high speaking rate detected ({round(wpm)} WPM) - possible hallucination")

    # 2. Repetition loops check
    has_loop = detect_repetition_loops(text)
    cleaned_text = text
    if has_loop:
        warnings.append("Repetitive hallucination loop detected in Whisper transcript")
        cleaned_text = deduplicate_repetitive_loops(text)

    # 3. Timestamp sanity check
    if word_timestamps:
        timestamps_count = len(word_timestamps)
        if timestamps_count > 0 and abs(timestamps_count - word_count) > word_count * 0.5:
            warnings.append(f"Word timestamp count mismatch: {timestamps_count} timestamps vs {word_count} words")

    passed = len(warnings) == 0
    return {
        "passed": passed,
        "warnings": warnings,
        "repetition_loop_detected": has_loop,
        "word_count": len(cleaned_text.split()),
        "wpm": round(wpm, 1),
        "cleaned_text": cleaned_text,
    }
